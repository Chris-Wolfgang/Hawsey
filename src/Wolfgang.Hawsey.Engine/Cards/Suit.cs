namespace Wolfgang.Hawsey.Engine;

/// <summary>
/// Represents the four suits in a standard deck.
/// Suits are paired by color: Hearts/Diamonds (red) and Clubs/Spades (black).
/// </summary>
public enum Suit
{
    /// <summary>Red suit.</summary>
    Hearts = 0,

    /// <summary>Red suit.</summary>
    Diamonds = 1,

    /// <summary>Black suit.</summary>
    Clubs = 2,

    /// <summary>Black suit.</summary>
    Spades = 3
}
